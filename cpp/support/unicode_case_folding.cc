void AppendUnicodeSimpleCaseFold(
    TCodepoint lower, TCodepoint upper, std::vector<TCodepoint>* output
) {
  for (const CaseFoldRange& range : kCaseFoldRanges) {
    if (range.last < lower || range.first > upper) {
      continue;
    }
    TCodepoint first = range.first;
    if (first < lower) {
      TCodepoint steps = (lower - first + range.stride - 1) / range.stride;
      first += steps * range.stride;
    }
    TCodepoint last = std::min(upper, range.last);
    for (TCodepoint codepoint = first; codepoint <= last; codepoint += range.stride) {
      for (uint8_t index = 0; index < range.count; ++index) {
        output->push_back(codepoint + range.offsets[index]);
      }
    }
  }
}

