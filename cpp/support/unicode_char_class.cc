template <size_t N>
bool IsInRanges(TCodepoint codepoint, const CodepointRange (&ranges)[N]) {
  size_t left = 0;
  size_t right = N;
  while (left < right) {
    size_t middle = left + (right - left) / 2;
    if (codepoint < ranges[middle].first) {
      right = middle;
    } else if (codepoint > ranges[middle].last) {
      left = middle + 1;
    } else {
      return true;
    }
  }
  return false;
}

