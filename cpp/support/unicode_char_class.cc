bool IsUnicodeWhitespace(TCodepoint codepoint) { return IsInRanges(codepoint, kWhitespaceRanges); }

bool IsUnicodeAlphabetic(TCodepoint codepoint) {
  return IsInRanges(codepoint, kAlphanumericRanges) &&
         !IsInRanges(codepoint, kNonAlphabeticNumberRanges);
}

bool IsUnicodeAlphanumeric(TCodepoint codepoint) {
  return IsInRanges(codepoint, kAlphanumericRanges);
}

